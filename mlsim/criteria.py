"""Единый критерий успеха для записи, оценки и витрины.

Раньше эта функция была скопирована в три файла (`eval_sim.py`,
`record_dataset.py`, `make_demo_gif.py`). Копии совпадали, но ничто этого не
гарантировало, а через `record_dataset.py` тот же код служит приёмкой датасета —
разъехавшись, они молча начали бы считать по-разному.

Пороги ужесточены: было `XY < 0.05, z < 0.06`, стало `XY < 0.04, z < 0.045`.
Причина: у коробки верх бортика на z = 0.044, полуразмер кубика 0.014, значит
кубик, ЛЕЖАЩИЙ НА БОРТИКЕ, имеет z = 0.058 < 0.06 и при радиусе меньше 5 см
засчитывался как «в коробке». Проверено в MuJoCo: такой кубик устойчиво лежит
там всю попытку. Порог по высоте при этом вообще не работал — z < 0.06
выполняется и для кубика на столе (z = 0.014), то есть различал только радиус.

Настоящие успехи лежат на дне коробки: z = 0.022, радиус 0.005–0.034 —
все проходят и под новый порог. Ни одна из ранее засчитанных попыток не
теряется, но ложноположительный путь закрыт.
"""

import mujoco
import numpy as np

from expert import CUBES

XY_MAX = 0.04     # радиус от центра коробки; след коробки — полуразмер 0.055
Z_MAX = 0.045     # верх бортика 0.044, дно 0.008; кубик на дне даёт z = 0.022


def cube_xyz(model, data, color: str) -> np.ndarray:
    """Координаты центра кубика — их стоит писать в отчёт, а не только вердикт."""
    bid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, CUBES[color]["body"])
    return np.array(data.xpos[bid], dtype=float)


def cube_in_bin(model, data, color: str, bin_site: int,
                xy_max: float = XY_MAX, z_max: float = Z_MAX) -> bool:
    cube = cube_xyz(model, data, color)
    bin_xy = data.site_xpos[bin_site][:2]
    return bool(np.linalg.norm(cube[:2] - bin_xy) < xy_max and cube[2] < z_max)
